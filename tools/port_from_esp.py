POLICY_FILES = ("default", "getup_sku1", "sku1v2_recovery")   # what firmware-dev builds in (main/rl/policies)
MPXP_FLAG_REMOTE = 0x40000000
KEEP_FIXTURES = 6       # of the file's 32: the MCU checks Linux's network against these at every load


def strip_policy(data):
    """the .mpxp without its weights, for the MCU: the network runs on Linux (python/policy_net.py).
    Same header (flag MPXP_FLAG_REMOTE, its own size and crc), then everything after the layers."""
    hdr = bytearray(data[:640])
    n_layers = struct.unpack_from("<I", hdr, 80)[0]
    dims = struct.unpack_from("<9I", hdr, 84)
    floats = sum(dims[l] * dims[l + 1] + dims[l + 1] for l in range(n_layers))
    rest = data[640 + 4 * floats:]
    # the self-test's fixtures: the first KEEP_FIXTURES of them (a 10-step history makes each 1.8 KB)
    n_fix, = struct.unpack_from("<I", hdr, 128)
    keep = min(n_fix, KEEP_FIXTURES)
    obs_b, act_b = 4 * n_fix * dims[0], 4 * n_fix * 12
    rest = (rest[:4 * keep * dims[0]] + rest[obs_b:obs_b + 4 * keep * 12] + rest[obs_b + act_b:])
    struct.pack_into("<I", hdr, 128, keep)
    flags = struct.unpack_from("<I", hdr, 124)[0] | MPXP_FLAG_REMOTE
    struct.pack_into("<I", hdr, 124, flags)
    out = bytearray(hdr) + rest
    struct.pack_into("<I", out, 8, len(out))
    struct.pack_into("<I", out, 12, zlib.crc32(bytes(out[16:])) & 0xFFFFFFFF)
    return bytes(out)


def port_policy(esp):
    """the RL runner (policy_run.cc, policy_core.c, http_policy.cc): on the MCU, the networks on Linux"""
    rdir = os.path.join(esp, "main", "rl")
    note = HEADER_NOTE
    t = read(os.path.join(rdir, "policy_core.h"))
    t = t.replace("#define MPXP_DEC_MAGIC", "#define MPXP_FLAG_REMOTE 0x40000000u   /* UNO Q: no weights here, the network runs on Linux "
                  "(port_from_esp.py strip_policy, policy_remote.cpp) */\n#define MPXP_DEC_MAGIC", 1)
    t = t.replace("/** Check and index a file.", "/** UNO Q: the network of a MPXP_FLAG_REMOTE file, on Linux (policy_remote.cpp). */\n"
                  "void mpx_pol_remote_forward(const pol_net_t *net, const float *obs, float act[POL_ACT]);\n\n"
                  "/** Check and index a file.", 1)
    assert "mpx_pol_remote_forward" in t and "MPXP_FLAG_REMOTE" in t
    write("policy_core.h", note.format(src="main/rl/policy_core.h") + plumb(t, False))

    t = read(os.path.join(rdir, "policy_core.c"))
    old = """        out->W[l] = p + floats;
        floats += (size_t)in * o;
        out->b[l] = p + floats;
        floats += o;"""
    assert old in t
    t = t.replace(old, """        if (!(h->flags & MPXP_FLAG_REMOTE)) {   /* UNO Q: a stripped file has no weights (port_from_esp.py) */
            out->W[l] = p + floats;
            floats += (size_t)in * o;
            out->b[l] = p + floats;
            floats += o;
        }""")
    old = """    const mpxp_header_t *h = net->h;
    float *x = work, *y = work + net->max_width;"""
    assert old in t
    t = t.replace(old, """    const mpxp_header_t *h = net->h;
    if (!net->W[0] && !net->Wq[0]) {          /* UNO Q: the network is on Linux */
        mpx_pol_remote_forward(net, obs, act);
        return;
    }
    float *x = work, *y = work + net->max_width;""")
    write("policy_core.c", note.format(src="main/rl/policy_core.c") + with_math(plumb(t, False)))
    write("mpx_policy.h", note.format(src="main/rl/mpx_policy.h") + plumb(read(os.path.join(rdir, "mpx_policy.h")), False))

    t = read(os.path.join(rdir, "policy_run.cc"))
    a = t.index('extern "C" {\nextern const uint8_t default_mpxp_start[]')
    b = t.index("}\n", t.index("#endif\n}", a)) + 2
    t = t[:a] + '#include "policy_files.h"   /* the built-in files, without weights (port_from_esp.py) */\n' + t[b:]
    t = t.replace('#include "voice/voice_glue.h"', '#include "voice_glue.h"      /* no voice on the UNO Q: no-ops */')
    old = """    *bytes_int = 0;
    *bytes_all = 0;
    for (uint32_t l = 0; l < MPXP_MAX_LAYERS; ++l) blk[l] = nullptr;"""
    assert old in t
    t = t.replace(old, old + """
    if (!net->W[0]) return true;          /* UNO Q: the weights are on Linux (MPXP_FLAG_REMOTE) */""", 1)
    old = """    const char *err = pol_parse(file, len, &net);
    if (err) {
        if (why) std::snprintf(why, why_len, "%s", err);
        return ESP_ERR_INVALID_ARG;
    }"""
    assert old in t
    t = t.replace(old, old + """
    if (!net.W[0]) bits = 32;             /* UNO Q: Linux runs the file's floats */""", 1)
    t = no_files(t)
    # <algorithm> trips gcc 15's -Wtemplate-body under the Zephyr flags; only std::sort needs it here
    assert "#include <algorithm>" in t and t.count("std::sort(v, v + n);") == 1
    t = t.replace("#include <algorithm>", "#include <bits/stl_algobase.h>   /* std::min / max / swap (port_from_esp.py) */")
    t = t.replace("std::sort(v, v + n);", "for (int i = 1; i < n; ++i) {        /* insertion sort (was std::sort) */\n"
                  "        const float x = v[i];\n        int j = i - 1;\n"
                  "        while (j >= 0 && v[j] > x) { v[j + 1] = v[j]; --j; }\n        v[j + 1] = x;\n    }")
    write("policy_run.cpp", note.format(src="main/rl/policy_run.cc") + with_math(plumb(t)))

    # the built-in files without their weights
    out_c = ['/* GENERATED by tools/port_from_esp.py: firmware-dev main/rl/policies/*.mpxp without their weights',
             ' * (MPXP_FLAG_REMOTE). The full files are python/policies/: Linux runs the networks. */',
             '#include "policy_files.h"', '']
    out_h = ['/* GENERATED by tools/port_from_esp.py (policy_files.c) */', '#pragma once', '#include <stdint.h>',
             '#ifdef __cplusplus', 'extern "C" {', '#endif']
    pdir = os.path.join(PYDIR, "policies")
    os.makedirs(pdir, exist_ok=True)
    for name in POLICY_FILES:
        src = os.path.join(rdir, "policies", name + ".mpxp")
        if not os.path.isfile(src):
            print("  (no %s.mpxp in firmware-dev)" % name)
            continue
        data = read_bin(src)
        with open(os.path.join(pdir, name + ".mpxp"), "wb") as f:
            f.write(data)
        st = strip_policy(data)
        body = ",".join("0x%02x" % c for c in st)
        out_c.append("const uint8_t mpx_pol_%s[%d] __attribute__((aligned(4))) = {%s};" % (name, len(st), body))
        out_h.append("extern const uint8_t mpx_pol_%s[%d];" % (name, len(st)))
        out_h.append("#define %s_mpxp_start (mpx_pol_%s)" % (name, name))
        out_h.append("#define %s_mpxp_end (mpx_pol_%s + %d)" % (name, name, len(st)))
        if name != "default":
            out_h.append("#define MPX_POLICY_HAVE_%s 1" % name.upper())
        print("  policy %s: %d bytes, %d on the MCU" % (name, len(data), len(st)))
    out_h += ["#ifdef __cplusplus", "}", "#endif", ""]
    write("policy_files.c", "\n".join(out_c) + "\n")
    write("policy_files.h", "\n".join(out_h))

    # /v1/policy: http_policy.cc's handlers, inside mcu_http.cpp's namespace
    t = read(os.path.join(esp, "main", "network", "http_policy.cc"))
    a = t.index("namespace {")
    b = t.index("int network::register_policy_routes")
    body = t[a:b]
    routes = re.findall(r'\{ "(/v1/policy[^"]*)",\s*HTTP_\w+,\s*"(\w+)",\s*(\w+)\s*\}', t)
    assert routes, "policy route table changed"
    table = "#define MPX_ROUTES_POLICY \\\n" + "\n".join('    { "%s", "%s", %s }, \\' % (m, u, f) for u, m, f in routes) + "\n    /* end */\n"
    write("mcu_http_policy_inc.h", HEADER_NOTE.format(src="main/network/http_policy.cc (handlers)") +
          "/* Included by mcu_http.cpp inside its own namespace, after the httpd shim. */\n" +
          no_files(plumb(body)) + "\n" + table)

    # cJSON (ESP-IDF's json component; the same library)
    cj = os.path.join(esp, "managed_components", "cjson")
    if not os.path.isdir(cj):
        if os.path.isfile(os.path.join(SKETCH, "cJSON.c")):
            print("  (no %s: keeping sketch/cJSON.c)" % cj)
            return
        raise SystemExit("cJSON missing: put cJSON.c / cJSON.h (github.com/DaveGamble/cJSON) in %s" % cj)
    for name in ("cJSON.c", "cJSON.h"):
        t = read(os.path.join(cj, name))
        if name == "cJSON.c":
            # the ctype functions, not newlib's table macros (_ctype_ is not something a UNO Q sketch can link)
            assert "#include <ctype.h>" in t
            t = t.replace("#include <ctype.h>", "#include <ctype.h>\n#undef isdigit\n#undef isspace\n#undef isxdigit\n"
                          "#undef isalpha\n#undef isalnum\n#undef isprint\n#undef tolower\n#undef toupper", 1)
        write(name, "/* COPIED by tools/port_from_esp.py from cJSON (MIT) */\n" + t)


def no_files(t):
    """the MCU has no file system: the run logs' files (LittleFS on the ESP) fail to open, as with a full disk"""
    for f in ("fopen", "fclose", "fprintf", "fputs", "fputc", "fread", "fwrite", "fflush"):
        t = re.sub(r"(?<![A-Za-z_])(?:std::)?%s\(" % f, "mpx_%s(" % f, t)
    return t


def read_bin(p):
    with open(p, "rb") as f:
        return f.read()


def port_trajopt(esp):
    """tj_meta.h (names, timing) for the sketch + tj_tables.bin (rows) for Linux"""
    src = read(os.path.join(esp, "main", "robot", "trajopt_jump.h"))
    arrays = {}
    for m in re.finditer(r"static const int16_t (TJ_DEG10_\d+)\[(\d+)\]\[12\] = \{(.*?)\n\};", src, re.S):
        name, n, body = m.group(1), int(m.group(2)), m.group(3)
        nums = [int(x) for x in re.findall(r"-?\d+", body)]
        assert len(nums) == n * 12, name
        arrays[name] = (n, nums)
    tm = re.search(r"static const tj_table_t TJ_TABLES\[\] = \{(.*?)\n\};", src, re.S)
    rows = [r.strip() for r in tm.group(1).strip().split("\n") if r.strip().startswith("{")]
    meta = []
    blob = bytearray()
    index = []
    for r in rows:
        # { "name", "note", frames, plan_start, tune_preset, TJ_DEG10_k, frame_ms, character, "label", show },
        m = re.match(r'\{\s*("(?:[^"\\]|\\.)*")\s*,\s*("(?:[^"\\]|\\.)*")\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,'
                     r'\s*(TJ_DEG10_\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*("(?:[^"\\]|\\.)*")\s*,\s*(-?\d+)\s*\}', r)
        assert m, r[:80]
        name, note, frames, plan, tune, arr, fms, char, label, show = m.groups()
        n, nums = arrays[arr]
        assert n == int(frames)
        index.append((len(blob), n))
        blob += struct.pack("<%dh" % len(nums), *nums)
        meta.append('    { %s, %s, %s, %s, %s, nullptr, %s, %s, %s, %s },' % (name, note, frames, plan, tune, fms, char, label, show))
    head = re.search(r"(#define TJ_FRAME_MS.*?\} tj_table_t;)", src, re.S).group(1)
    out = (HEADER_NOTE.format(src="main/robot/trajopt_jump.h") +
           "/* Table METADATA only: the rows (deg10) live on Linux (python/tj_tables.bin) and\n"
           " * reach tj_play() through tj_stream.h, so deg10 is nullptr here. */\n"
           "#ifndef TJ_META_H\n#define TJ_META_H\n\n#include <stdint.h>\n#include \"tj_stream.h\"\n\n" + head +
           "\n\nstatic const tj_table_t TJ_TABLES[] = {\n" + "\n".join(meta) + "\n};\n"
           "#define TJ_NTABLES ((int)(sizeof(TJ_TABLES) / sizeof(TJ_TABLES[0])))\n\n#endif\n")
    write("tj_meta.h", out)
    # tj_tables.bin: "MPXTJ1", count, then (offset, rows) per table, then int16 rows
    hdr = bytearray(b"MPXTJ1") + struct.pack("<H", len(index))
    base = len(hdr) + 8 * len(index)
    for off, n in index:
        hdr += struct.pack("<II", base + off, n)
    path = os.path.join(PYDIR, "tj_tables.bin")
    with open(path, "wb") as f:
        f.write(bytes(hdr) + bytes(blob))
    print("  wrote python/tj_tables.bin", len(hdr) + len(blob), "bytes,", len(index), "tables")
    if "TJ_NTABLES" not in src:
        pass


def port_http(esp):
    """the robot + Servo Studio routes of http_server.cc"""
    src = read(os.path.join(esp, "main", "network", "http_server.cc"))
    lines = src.split("\n")

    def block(start_pat, end_pat):
        s = next(i for i, l in enumerate(lines) if re.search(start_pat, l))
        e = next(i for i in range(s + 1, len(lines)) if re.search(end_pat, lines[i]))
        return "\n".join(lines[s:e])

    parts = [
        block(r"^static std::string json_escape\(const std::string &s\)$", r"^/\* GET /v1/fs/list"),
        block(r"^static std::string json_get_str\(const char \*body, const char \*key\)$", r"^/\* The one gait name table|^static const char \*gait_cmd_to_name"),
        block(r"^static const char \*gait_cmd_to_name", r"^/\* /v1/agent/permissions"),
        block(r"^/\* POST /v1/robot/joy", r"^/\* GET /v1/pi/status"),
        block(r"^/\* POST /v1/robot/config", r"^/\* GET /v1/trace"),
        block(r"^static int studio_qint", r"^/\* ═+\n?$|^ \*  WiFi config API"),
    ]
    body = "\n\n".join(parts)
    # the WiFi banner's opening line ends the studio block one line late
    body = re.sub(r"\n/\* ═+\s*$", "\n", body)
    # the route table: the ESP's register_api() lines whose handler came along
    routes = []
    for m in re.finditer(r'register_api\(s_server,\s*"(GET|POST)",\s*"(/v1/(?:robot|studio)/[^"]+)",\s*HTTP_\w+,\s*(\w+)\)', src):
        meth, uri, fn = m.groups()
        if re.search(r"^static esp_err_t %s\(httpd_req_t \*" % fn, body, re.M):
            routes.append('    { "%s", "%s", %s }, \\' % (meth, uri, fn))
        else:
            print("  route left out (handler not ported):", meth, uri, fn)
    table = "\n\n/* the ESP's register_api() calls for these handlers */\n#define MPX_ROUTES_ROBOT \\\n" + "\n".join(routes) + "\n\n"
    out = (HEADER_NOTE.format(src="main/network/http_server.cc (robot + Servo Studio routes)") +
           "/* Included by mcu_http.cpp inside its own namespace, after the httpd shim. */\n\n" + plumb(body) + table)
    write("mcu_http_routes_inc.h", out)



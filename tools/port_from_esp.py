    t = t[:a] + "/* bmi270_sensor_create / _del: the ESP wrapper, left out (port_from_esp.py) */\n" + t[b:]
    assert '#include "common/common.h"' in t
    t = t.replace('#include "common/common.h"', "")   # the ESP wrapper's helpers
    write("bmi270.c", note.format(src="managed_components/espressif2022__bmi270/bmi270.c") + t)
    for name in ("bmm150.h", "bmm150_defs.h", "bmm150.c"):
        t = read(os.path.join(bmm, name))
        if name == "bmm150_defs.h":
            t = t.replace("#include <linux/types.h>", "")
        write(name, note.format(src="managed_components/tangyumei3535__bmm150_sensorapi/" + name) + t)



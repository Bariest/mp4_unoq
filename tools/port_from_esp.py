#!/usr/bin/env python3
"""port_from_esp.py -- bring the ESP firmware's movement code into the UNO Q sketch.

    python tools/port_from_esp.py <path to mpv2onlyRL>

The UNO Q runs the SAME movement code as the ESP32-S3 (main/robot/robot.cc and
friends) and the SAME Servo Studio / robot HTTP handlers (main/network/
http_server.cc). This script copies them into sketch/ with only the changes the
different plumbing needs, so a change on the ESP side is brought over by running
it again:

  * includes are flattened ("robot/robot.h" -> "robot.h") and every ESP-IDF /
    FreeRTOS header is pointed at shim_esp.h (sketch/shim_esp.*), which maps them
    onto Zephyr and the Arduino core;
  * float maths go through mpx_math.h (the UNO Q core 0.51 does not export sinf /
    cosf to sketches);
  * driver_board.c keeps its protocol code; only the two functions that touch
    the ESP SPI driver are replaced (spi_port.cpp does the transfers);
  * the 600 KB of TrajOpt / Character tables do not fit the MCU: the sketch gets
    their names and timing only (tj_meta.h), and the rows are streamed from Linux
    while a move plays (python/tj_tables.bin, written here);
  * the robot and Servo Studio routes of http_server.cc become mcu_http_routes_inc.h,
    served over the Bridge (mcu_http.cpp) so their JSON is byte-for-byte the ESP's.

Hand-written files (shim_esp.*, spi_port.cpp, imu_port.cpp, mcu_http.cpp,
tj_stream.*, board_config.h, mpx_math.h, sketch.ino) are not touched.
"""
import os
import re
import struct
import zlib
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
SKETCH = os.path.join(APP, "sketch")
PYDIR = os.path.join(APP, "python")

ESP_HEADERS = [
    "freertos/FreeRTOS.h", "freertos/task.h", "freertos/semphr.h", "freertos/idf_additions.h",
    "esp_log.h", "esp_timer.h", "esp_err.h", "esp_cpu.h", "esp_rom_sys.h", "esp_system.h",
    "nvs.h", "nvs_flash.h", "driver/gpio.h", "driver/spi_master.h", "sdkconfig.h",
]

HEADER_NOTE = ("/* GENERATED by tools/port_from_esp.py from mpv2onlyRL/{src} - edit the ESP original\n"
               " * and run the script again; only the plumbing differs (see the script). */\n")


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def write(name, text):
    path = os.path.join(SKETCH, name)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("  wrote", os.path.relpath(path, APP), len(text), "bytes")


def plumb(text, cpp=True):
    """the changes every copied file gets"""
    for h in ESP_HEADERS:
        text = text.replace('#include "%s"' % h, '#include "shim_esp.h"')
    # any other ESP-IDF / FreeRTOS header (esp_heap_caps.h, esp_random.h, freertos/queue.h, ...)
    text = re.sub(r'#include "(?:freertos/[A-Za-z_]+|esp_(?:heap_caps|random|check|attr|idf_version|mac|chip_info)|nvs(?:_flash)?)\.h"',
                  '#include "shim_esp.h"', text)
    # LVGL lives in sketch/src/lvgl (tools/vendor_lvgl.py)
    text = text.replace('#include "lvgl.h"', '#include "src/lvgl/lvgl.h"')
    text = re.sub(r'#include "((?:libs|misc)/[A-Za-z0-9_/]+\.h)"', r'#include "src/lvgl/src/\1"', text)
    text = re.sub(r'#include "(?:robot|rl|display|platform|network|util)/([A-Za-z0-9_]+\.(?:h|inc))"', r'#include "\1"', text)
    text = text.replace('#include "robot/trajopt_jump.h"', '#include "tj_meta.h"')
    text = text.replace('#include "trajopt_jump.h"', '#include "tj_meta.h"')
    if cpp:
        for a, b in (("std::sin(", "mpx_sin("), ("std::cos(", "mpx_cos("), ("std::lrintf(", "mpx_lrintf("),
                     ("std::lround(", "mpx_lround("), ("std::fmin(", "mpx_fmin("), ("std::fmax(", "mpx_fmax(")):
            text = text.replace(a, b)
    return text


def with_math(text):
    """mpx_math.h goes after the system headers: libstdc++'s <cmath> #undefs C maths macros"""
    lines = text.split("\n")
    last = -1
    for i, l in enumerate(lines):
        if l.startswith("#include <"):
            last = i
    if last < 0:
        return '#include "mpx_math.h"\n' + text
    lines.insert(last + 1, '#include "mpx_math.h"   /* after the system headers (port_from_esp.py) */')
    return "\n".join(lines)


def replace_function(text, signature_regex, new_body_with_signature):
    """replace a top-level C function (signature line up to its closing brace at column 0)"""
    m = re.search(signature_regex, text, re.M)
    if not m:
        raise SystemExit("function not found: " + signature_regex)
    start = m.start()
    end = text.index("\n}\n", m.end()) + 3
    return text[:start] + new_body_with_signature + text[end:]


def port_robot(esp):
    rdir = os.path.join(esp, "main", "robot")
    # ---- straight copies (plumbing only)
    for src, dst, cpp, math in (
        ("robot.h", "robot.h", True, False),
        ("imu.h", "imu.h", True, False),
        ("alive.h", "alive.h", False, False),
        ("alive.c", "alive.c", False, True),
        ("stanford_gait.h", "stanford_gait.h", False, False),
        ("stanford_gait.cc", "stanford_gait.cpp", True, True),
        ("stanford_kinematics.h", "stanford_kinematics.h", False, False),
        ("stanford_kinematics.cc", "stanford_kinematics.cpp", True, True),
        ("mpx_robot.h", "mpx_robot.h", False, False),
        ("mpe_tables.h", "mpe_tables.h", False, False),
        ("longjump_table.h", "longjump_table.h", False, False),
        ("driver_board.h", "driver_board.h", False, False),
        ("battery.h", "battery.h", False, False),
        ("battery.cc", "battery.cpp", True, True),
    ):
        t = plumb(read(os.path.join(rdir, src)), cpp)
        if src == "driver_board.h":
            # SERVO_BOARD comes from this robot's board_config.h, which the ESP
            # header does not include (it would default to 2 = FR/RR swapped)
            t = t.replace("#include <stdbool.h>\n", "#include <stdbool.h>\n#include \"board_config.h\"   /* SERVO_BOARD (port_from_esp.py) */\n", 1)
            assert "board_config.h" in t
        if math:
            t = with_math(t)
        write(dst, HEADER_NOTE.format(src="main/robot/" + src) + t)

    # ---- imu.cc: the ESP's BMI270 + BMM150 driver; i2c_master on Wire (shim_i2c.h)
    t = read(os.path.join(rdir, "imu.cc"))
    for h in ('#include "driver/i2c_master.h"', '#include "platform/shared_i2c.h"'):
        assert h in t, h
        t = t.replace(h, '#include "shim_i2c.h"')
    t = plumb(t)
    write("imu.cpp", HEADER_NOTE.format(src="main/robot/imu.cc") + with_math(t))

    # ---- robot.cc: plumbing; the gait task gets a Zephyr thread through the shim
    t = plumb(read(os.path.join(rdir, "robot.cc")))
    # the App Lab build copies only .c/.cpp/.h/... into its build folder, not .inc
    assert '#include "moves_mpe.inc"' in t
    t = t.replace('#include "moves_mpe.inc"', '#include "moves_mpe_inc.h"')
    write("robot.cpp", HEADER_NOTE.format(src="main/robot/robot.cc") + with_math(t))

    # ---- moves_mpe.inc: the TrajOpt player reads streamed rows, not a table in flash
    t = plumb(read(os.path.join(rdir, "moves_mpe.inc")))
    body_start = t.index("void tj_play(int k, GaitCmd cmd)")
    body_end = t.index("\n}\n", body_start) + 3
    tp = t[body_start:body_end]
    old_open = "    const tj_table_t *T = &TJ_TABLES[k];\n"
    assert old_open in tp, "tj_play changed on the ESP side: update port_from_esp.py"
    tp = tp.replace(old_open, old_open +
                    "    // UNO Q: the rows come from Linux (tj_stream.cpp); wait for the first ones.\n"
                    "    if (!tj_stream_open(k, T->frames)) {\n"
                    "        ESP_LOGW(TAG, \"trajopt '%s': no rows from Linux - skipped\", T->name);\n"
                    "        return;\n"
                    "    }\n", 1)
    # rows f / f2 of the playback loop
    old_row = "            const float a = T->deg10[f][ch - 1], b = T->deg10[f2][ch - 1];"
    assert old_row in tp
    tp = tp.replace("        for (int ch = 1; ch <= 12; ++ch) {\n" + old_row,
                    "        const int16_t *rf = tj_stream_row(f), *rf2 = tj_stream_row(f2);\n"
                    "        if (!rf || !rf2) { aborted = true; ESP_LOGW(TAG, \"trajopt: Linux stopped sending rows\"); break; }\n"
                    "        for (int ch = 1; ch <= 12; ++ch) {\n"
                    "            const float a = rf[ch - 1], b = rf2[ch - 1];", 1)
    # the first row (soft start) and the last one (the stand / the park pose)
    tp = tp.replace("T->deg10[T->frames - 1][ch - 1]", "tj_stream_last()[ch - 1]")
    tp = tp.replace("T->deg10[0][ch - 1]", "tj_stream_first()[ch - 1]")
    assert "deg10" not in tp, "tj_play reads deg10 in a new way: update port_from_esp.py"
    old_end = "    if (pushed) gains_pop();\n    if (cmd == GaitCmd::CharShow) play_mark(\"charshow\");"
    assert old_end in tp
    tp = tp.replace(old_end, "    tj_stream_close();\n" + old_end, 1)
    t = t[:body_start] + tp + t[body_end:]
    assert "deg10[" not in t.replace("deg10[12]", ""), "another reader of the TrajOpt rows: update port_from_esp.py"
    write("moves_mpe_inc.h", HEADER_NOTE.format(src="main/robot/moves_mpe.inc") + t)

    # ---- driver_board.c: protocol kept, SPI plumbing replaced
    t = plumb(read(os.path.join(rdir, "driver_board.c")), cpp=False)
    t = t.replace('#include "driver_board.h"\n', '#include "driver_board.h"\n#include "spi_port.h"\n', 1)
    t = replace_function(t, r"^static esp_err_t spi_xfer\(uint8_t board, uint8_t size, uint8_t \*tx, uint8_t \*rx\)\n\{",
                         "static esp_err_t spi_xfer(uint8_t board, uint8_t size, uint8_t *tx, uint8_t *rx)\n{\n"
                         "    /* UNO Q: Arduino SPI on D13/D11/D12, chip selects D9/D10/D8/D7 (spi_port.cpp) */\n"
                         "    return mpx_spi_xfer(board, tx, rx, size) ? ESP_OK : ESP_FAIL;\n}\n")
    t = replace_function(t, r"^bool driver_board_init\(void\)\n\{",
                         "bool driver_board_init(void)\n{\n"
                         "    if (s_lock) {\n"
                         "        ESP_LOGW(TAG, \"driver_board_init() called twice - ignoring\");\n"
                         "        return true;\n"
                         "    }\n"
                         "    s_lock = xSemaphoreCreateMutex();\n"
                         "    if (!s_lock) {\n"
                         "        ESP_LOGE(TAG, \"mutex alloc failed\");\n"
                         "        return false;\n"
                         "    }\n"
                         "    /* UNO Q: the bus, its pins and its edge speed are set up by spi_port.cpp */\n"
                         "    if (!mpx_spi_begin()) return false;\n"
                         "    ESP_LOGI(TAG, \"driver board SPI: %d kHz, edge speed %d (0 = softest .. 3)\",\n"
                         "             (int)(mpx_spi_hz() / 1000), mpx_spi_edge());\n"
                         "    driver_board_power(true);\n"
                         "    return true;\n"
                         "}\n")
    if "static const char *bc_cn(int board)" in t:
        # the boot check names the connector of a board from the ESP's GPIO numbers
        t = replace_function(t, r"^static const char \*bc_cn\(int board\)\n\{",
                             "static const char *bc_cn(int board)\n{\n"
                             "    /* UNO Q carrier board: board_config.h */\n"
                             "    static const char *const cn[4] = { SERVO_BOARD0_CN, SERVO_BOARD1_CN, SERVO_BOARD2_CN, SERVO_BOARD3_CN };\n"
                             "    return (board >= 0 && board < 4) ? cn[board] : \"CN?\";\n"
                             "}\n")
    write("driver_board.c", HEADER_NOTE.format(src="main/robot/driver_board.c") + with_math(t))


def port_bosch(esp):
    """Bosch's BMI270 and BMM150 sensor APIs, from the ESP build's managed_components"""
    mc = os.path.join(esp, "managed_components")
    bmi = os.path.join(mc, "espressif2022__bmi270")
    bmm = os.path.join(mc, "tangyumei3535__bmm150_sensorapi")
    if not os.path.isdir(bmi) or not os.path.isdir(bmm):
        raise SystemExit("managed_components/espressif2022__bmi270 or tangyumei3535__bmm150_sensorapi missing:"
                         " build the ESP project once (idf.py reconfigure) so they are downloaded")
    note = "/* COPIED by tools/port_from_esp.py from {src} (BSD-3-Clause, Bosch Sensortec) */\n"
    for name in ("bmi2_defs.h", "bmi270.h", "bmi2.c"):
        t = read(os.path.join(bmi, name))
        if name == "bmi2.h":
            pass
        write(name, note.format(src="managed_components/espressif2022__bmi270/" + name) + t)
    t = read(os.path.join(bmi, "bmi2.h"))
    esp_inc = ['#include "freertos/FreeRTOS.h"', '#include "freertos/task.h"', '#include "esp_log.h"',
               '#include "esp_check.h"', '#include "i2c_bus.h"']
    for h in esp_inc:
        assert h in t, h
        t = t.replace(h, "")
    t = t.replace('#include "bmi2_defs.h"', '#ifndef CONFIG_SENSOR_BMI270\n#define CONFIG_SENSOR_BMI270 1   /* the component\'s Kconfig default */\n#endif\n#include "bmi2_defs.h"\n#include "shim_esp.h"\ntypedef void *i2c_bus_handle_t;   /* the ESP wrapper\'s, unused here */', 1)
    write("bmi2.h", note.format(src="managed_components/espressif2022__bmi270/bmi2.h") + t)
    # bmi270.c without the ESP wrapper (bmi270_sensor_create/del on the i2c_bus component)
    t = read(os.path.join(bmi, "bmi270.c"))
    a = t.index("esp_err_t bmi270_sensor_create(")
